#!/bin/bash
#
# piBrick Driver Installer
# Interactive installer for piBrick PocketCM5 drivers and tools
#
# Usage:
#   ./install.sh              # Interactive mode
#   ./install.sh --install x  # Non-interactive (see --help)
#
set -euo pipefail

# ── Colors (ANSI-C quoting: $'...' interprets \033 as the escape byte) ───────────
RED=$'\033[0;31m'
GREEN=$'\033[0;32m'
YELLOW=$'\033[1;33m'
BLUE=$'\033[0;34m'
CYAN=$'\033[0;36m'
BOLD=$'\033[1m'
RESET=$'\033[0m'

info()    { echo -e "${BLUE}[INFO]${RESET} $*"; }
success() { echo -e "${GREEN}[OK]${RESET} $*"; }
warn()    { echo -e "${YELLOW}[WARN]${RESET} $*"; }
error()   { echo -e "${RED}[ERROR]${RESET} $*" >&2; }

# Copy src to dst only when they differ (avoids "same file" errors from cp/install).
# Preserves permissions and ownership like cp -p.
safe_cp() {
    local src="$1" dst="$2"
    [ -f "$src" ] || { error "safe_cp: source not found: $src"; return 1; }
    if [ -f "$dst" ] && cmp -s "$src" "$dst"; then
        # Even if bytes match, make sure exec bit is set if source has it.
        if [ -x "$src" ] && [ ! -x "$dst" ]; then
            chmod +x "$dst"
        fi
        return 0
    fi
    cp -p "$src" "$dst"
    # Ensure exec bit is set if source has it (cp -p preserves mode, but be safe).
    if [ -x "$src" ] && [ ! -x "$dst" ]; then
        chmod +x "$dst"
    fi
}

# ── Config paths ───────────────────────────────────────────────────────────────
