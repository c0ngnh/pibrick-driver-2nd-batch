# ── Calibration functions (must be defined before use) ──────────────────────────
# The status JSON (calibration_status.json) is generated by `battery-auto-calibrator
# --check`. It only refreshes when the user explicitly runs --check or --apply.
# After --reset-calibration the CSV is fresh but the JSON still describes the
# previous run's stats, which is misleading. To keep --status-calibration honest,
# refresh the JSON from the live CSV whenever it's stale (CSV mtime > JSON mtime).
status_calibration() {
	local csv=/var/log/bq25890_battery/calibration_data.csv
	local status_json=/var/log/bq25890_battery/calibration_status.json

	if [ ! -f "$status_json" ] && [ ! -f "$csv" ]; then
		echo "No calibration data found."
		echo "Run calibration logger first: sudo systemctl start pibrick-battery-calibration"
		return 1
	fi

	# Re-derive the JSON from the live CSV when the JSON is stale. Without
	# this, --status-calibration would report stats from the previous run
	# (or from before --reset-calibration wiped the CSV).
	#
	# The staleness check is exact: --check writes JSON with a mtime
	# later than the CSV it just analyzed, so after a refresh the
	# `[ "$csv" -nt "$status_json" ]` condition becomes false until the
	# logger appends a new row. No additional rate-limit needed.
	if [ -f "$csv" ] && { [ ! -f "$status_json" ] || [ "$csv" -nt "$status_json" ]; }; then
		local calibrator
		if calibrator=$(find_battery_tool "battery-auto-calibrator.py" 2>/dev/null); then
			# --check re-analyzes the CSV and overwrites the JSON. Output is
			# suppressed so --status below prints the canonical summary instead.
			python3 "$calibrator" --check >/dev/null 2>&1 || true
		fi
	fi

	python3 "$PIBRICK_TOOLS_DIR/battery-auto-calibrator.py" --status 2>/dev/null || \
		cat "$status_json"
}

# ── Apply the calibrated OCV table ─────────────────────────────────────────────
# Forwards remaining arguments to battery-auto-calibrator.py so users can
# do `sudo pibrick-tools --apply-calibration --yes --no-ina228` etc.
apply_calibration() {
	info "Checking calibration status..."

	local calibrator
	if ! calibrator=$(find_battery_tool "battery-auto-calibrator.py"); then
		return 1
	fi

	# Strip the leading "--apply-calibration" so any args after it
	# become the calibrator's flags (e.g. --yes, --no-ina228,
	# --no-rebuild). Without TTY the "--yes" is implied.
	local extra=()
	for arg in "$@"; do
		case "$arg" in
			--apply-calibration) ;;
			*) extra+=("$arg") ;;
		esac
	done

	# If the user didn't pass --yes and there's no TTY (e.g. running
	# from a script or background), imply --yes so the command doesn't
	# hang forever waiting on stdin.
	if [ ! -t 0 ]; then
		local has_yes=0
		for a in "${extra[@]}"; do
			[ "$a" = "--yes" ] || [ "$a" = "-y" ] && has_yes=1
		done
		[ "$has_yes" = "0" ] && extra+=("--yes")
	fi

	python3 "$calibrator" --apply "${extra[@]}"
}

# ── Reset (truncate) calibration data ──────────────────────────────────────────
# Stops the logger service, deletes the per-session log files
# (calibration.log + calibration_data.csv), and restarts the service so the
# next row written is a fresh CSV header. Preserves calibration_status.json,
# calibration_metadata.json, and suggested_ocv_table.h — those are
# generated work-products, not raw input data, and disposing of them on
# every reset would be surprising.
#
# Idempotent: works whether the service is currently running or stopped.
# Refuses to do anything if the calibration component is not installed.
reset_calibration() {
	local log_dir=/var/log/bq25890_battery
	local log_file="$log_dir/calibration.log"
	local csv_file="$log_dir/calibration_data.csv"

	if [ ! -d "$log_dir" ] && [ ! -f /etc/systemd/system/pibrick-battery-calibration.service ]; then
		error "Calibration tooling not installed. Run: $0 --install calibration"
		return 1
	fi

	# Stop the logger so file handles are released and the truncated CSV
	# gets a fresh header on the first row.
	if systemctl is-active --quiet pibrick-battery-calibration.service 2>/dev/null; then
		info "Stopping calibration logger..."
		systemctl stop pibrick-battery-calibration.service || true
	fi

	mkdir -p "$log_dir"
	# Tighten the dir mode: install_calibration creates it via the bare
	# `mkdir -p` inherited from earlier versions, which leaves it 0777 and
	# lets any local user tamper with calibration data. 0755 + root-only
	# files stops that.
	chmod 0755 "$log_dir"

	local deleted=()
	for f in "$log_file" "$csv_file"; do
		if [ -f "$f" ]; then
			local before
			before=$(wc -c < "$f")
			rm -f "$f"
			deleted+=("$(basename "$f") (${before} bytes)")
		fi
	done

	if [ ${#deleted[@]} -gt 0 ]; then
		info "Deleted: ${deleted[*]}"
	else
		info "No prior calibration data found — nothing to delete"
	fi

	# Re-enable + start so the next row gets written under the new run.
	info "Starting calibration logger..."
	systemctl enable pibrick-battery-calibration.service 2>/dev/null || true
	systemctl start pibrick-battery-calibration.service 2>/dev/null || true

	success "Calibration data reset. New rows will be appended to a fresh CSV."
}

# ── Find a battery Python helper ───────────────────────────────────────────────
# Resolves the path to a Python helper under the battery tools dir, falling
# back to $PIBRICK_LIB/battery/ (the source tree) if the tools-dir copy
# is missing. Used for battery_set.py / battery-check.py / etc.
find_battery_tool() {
	local script="$1"
	for candidate in \
		"$PIBRICK_TOOLS_DIR/$script" \
		"$PIBRICK_LIB/battery/$script"; do
		if [ -f "$candidate" ]; then
			echo "$candidate"
			return 0
		fi
	done
	error "$script not installed. Run: $0 --install calibration"
	return 1
}

# ── Battery status (shows current params + persisted config) ──────────────────
battery_status() {
	info "Battery status & custom values"

	local battery_set
	if ! battery_set=$(find_battery_tool "battery_set.py"); then
		return 1
	fi

	echo
	echo -e "${BOLD}=== Current Driver Values (live) ===${RESET}"
	python3 "$battery_set" --show

	echo
	echo -e "${BOLD}=== Persisted Config (/etc/modprobe.d/pibrick-battery.conf) ===${RESET}"
	if [ -f /etc/modprobe.d/pibrick-battery.conf ]; then
		cat /etc/modprobe.d/pibrick-battery.conf
	else
		echo "(none — no values persisted yet)"
	fi

	echo
	echo -e "${BOLD}=== Driver Defaults (compile-time) ===${RESET}"
	python3 "$battery_set" --list 2>&1 | \
		grep -E "Driver Default" || true

	echo
	echo -e "${BOLD}=== Quick SOC Readout ===${RESET}"
	if [ -f /sys/class/power_supply/battery/capacity ]; then
		SOC=$(cat /sys/class/power_supply/battery/capacity)
		STATUS=$(cat /sys/class/power_supply/battery/status 2>/dev/null || echo "Unknown")
		V=$(($(cat /sys/class/power_supply/battery/voltage_now 2>/dev/null || echo 0) / 1000))
		I_UA=$(cat /sys/class/power_supply/battery/current_now 2>/dev/null || echo 0)
		I_MA=$(awk "BEGIN {printf \"%.0f\", ${I_UA}/1000}")
		echo "  SOC:        ${SOC}%"
		echo "  Status:     ${STATUS}"
		echo "  Voltage:    ${V} mV"
		echo "  Current:    ${I_MA} mA"
	else
		echo "  (battery power_supply not found — is the driver loaded?)"
	fi
}

# ── Battery configuration (interactive / non-interactive) ─────────────────────
battery_config() {
	local persist_flag=""
	local force_flag=""
	local extra_args=()

	# Parse remaining args after --battery-config
	shift 2>/dev/null || true
	while [ $# -gt 0 ]; do
		case "$1" in
		--persist) persist_flag="1" ;;
		--force)   force_flag="1" ;;
		--list)    extra_args+=("--list") ;;
		--list-verbose) extra_args+=("--list-verbose") ;;
		--show)    extra_args+=("--show") ;;
		*)         extra_args+=("$1") ;;
		esac
		shift
	done

	local battery_set
	if ! battery_set=$(find_battery_tool "battery_set.py"); then
		return 1
	fi

	# If no extra args, run interactive mode
	if [ ${#extra_args[@]} -eq 0 ]; then
		info "Launching interactive battery configuration..."
		# Need to be a TTY for interactive; just exec directly
		python3 "$battery_set"
		return $?
	fi

	# Non-interactive path: join split "<value> <unit>" into "<value><unit>"
	# e.g. "charge_full_uah" "3800" "mAh" → "charge_full_uah" "3800mAh"
	if [ "${#extra_args[@]}" -ge 3 ]; then
		case "${extra_args[2]}" in
			mAh|Ah|uAh|mA|A|uA|mV|V|uV|mΩ|Ω|uΩ|%|s|samples)
				extra_args[1]="${extra_args[1]}${extra_args[2]}"
				unset 'extra_args[2]'
				local merged=()
				for a in "${extra_args[@]}"; do
					[ -n "$a" ] && merged+=("$a")
				done
				extra_args=("${merged[@]}")
				;;
		esac
	fi

	local cmd=(python3 "$battery_set" "${extra_args[@]}")
	[ -n "$persist_flag" ] && cmd+=("--persist")
	[ -n "$force_flag" ] && cmd+=("--force")

	info "Running: ${cmd[*]}"
	"${cmd[@]}"
}

