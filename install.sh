# ── UPower fix ─────────────────────────────────────────────────────────────────
# /usr/libexec/upowerd is mapped as a text segment while the daemon is running,
# so any `cp` over it returns ETXTBSY. The whole patch must run with the daemon
# stopped; `restart_upower()` re-launches it at the end.
fix_upower() {
	# Require root — this function needs to stop/restart upowerd and write system files.
	# If we got here via `nohup bash install.sh --install upower` (without outer sudo),
	# re-invoke ourselves under sudo. The `-n` flag ensures we fail fast instead of
	# prompting for a password in non-interactive contexts.
	if [ "$(id -u)" != "0" ]; then
		if command -v sudo >/dev/null 2>&1 && sudo -n true 2>/dev/null; then
			exec sudo -n bash "$0" "$@"
		fi
		error "UPower fix requires root."
		error "Re-run: sudo $0 $*" >&2
		return 1
	fi

	info "Applying UPower KDE fix..."

	# Always unmask first — handles the case where a previous interrupted run
	# left the service masked. Then set the trap to clean up if WE mask it.
	unmask_upower

	# Set a trap so unmask runs on exit, error, or interrupt — prevents the
	# service from being left masked if the function is interrupted.
	trap unmask_upower EXIT
	trap 'unmask_upower; exit 130' INT
	trap 'unmask_upower; exit 143' TERM

	# Require KDE desktop (UPower belongs to the desktop session, not system services).
	if ! kde_packages_available; then
		error "KDE Plasma packages not installed."
		echo "  Run \`sudo pibrick-tools --install kde-mobile-desktop\` first to install KDE Plasma."
		return 1
	fi

	local UPowerD
	UPowerD=$(command -v upowerd 2>/dev/null || echo "/usr/libexec/upowerd")
	# Also check the alternative path used on Debian/Ubuntu
	if [ ! -f "$UPowerD" ]; then
		if [ -f /usr/lib/upower/upowerd ]; then
			UPowerD=/usr/lib/upower/upowerd
		elif [ -f /usr/libexec/upowerd ]; then
			UPowerD=/usr/libexec/upowerd
		fi
	fi
	if [ ! -f "$UPowerD" ]; then
		warn "upowerd binary not found — skipping."
		return 0
	fi

	if grep -qE "piBrick|DISABLED.*current_now" "$UPowerD" 2>/dev/null; then
		success "UPower already patched."
		restart_upower "$UPowerD"
		return 0
	fi

	stop_upower

	info "Patching UPower (rebuild from source)..."
	local UPVER=""
	# Try to read the daemon version in order of preference:
	#   1. upower --version     (CLI; works when package is installed)
	#   2. upowerd -v           (the daemon itself, may print version)
	#   3. dpkg-query           (package version as a stable fallback)
	# The CLI under sudo can fail for a few reasons (PATH, secure_path,
	# masked service in some setups), so chain fallbacks. With pipefail,
	# append || true on each command substitution so an empty result is
	# never treated as a script-fatal error.
	UPVER=$(upower --version 2>/dev/null | grep '^UPower daemon' | awk '{print $NF}' | tr -d '\n' || true)
	if [ -z "$UPVER" ] && [ -x "$UPowerD" ]; then
		UPVER=$("$UPowerD" --version 2>/dev/null | head -1 | tr -d '\n' || true)
	fi
	if [ -z "$UPVER" ]; then
		UPVER=$(dpkg-query -W -f='${Version}' upower 2>/dev/null | tr -d '\n' || true)
	fi
	[ -z "$UPVER" ] && UPVER="unknown"
	info "UPower daemon version: $UPVER"

	# git is required for cloning — install it first if missing.
	if ! command -v git >/dev/null 2>&1; then
		info "Installing git..."
		apt-get install -y git 2>/dev/null || true
	fi

	local UP_SRC=/tmp/upower-pibrick-src
	if [ ! -d "$UP_SRC/.git" ]; then
		rm -rf "$UP_SRC"
		# If we have a version, try the matching tag first. 'unknown' or an
		# empty UPVER skips directly to main. The previous behavior of always
		# trying "v<garbage>" first wasted a round-trip on every unknown case.
		local git_ok=0
		# We previously piped `git clone` through `grep -vE '^(Cloning|...)'`
		# which stripped ALL of git's output — including the progress bar
		# lines — so the user saw nothing for the entire duration of the
		# clone and assumed the script was hung. That led to people
		# Ctrl-C'ing out of a successful run, then re-running it on a
		# half-cloned state. Use `git clone --progress` so git writes
		# progress to stderr (which we already redirect to stdout), and
		# print every line as it arrives. The clone itself rarely takes
		# more than 30s on a fresh image; if it does, the user will see
		# live progress and won't be tempted to abort.
		if [ -n "$UPVER" ] && [ "$UPVER" != "unknown" ]; then
			info "Cloning UPower source (tag v$UPVER) — this may take a few minutes..."
			git clone --progress --depth=1 --branch="v$UPVER" \
				https://gitlab.freedesktop.org/upower/upower.git "$UP_SRC" 2>&1 \
				| sed 's/^/    /' \
				|| true
			if [ -d "$UP_SRC/.git" ]; then
				git_ok=1
			else
				info "Tag v$UPVER not found in upstream."
			fi
		fi
		if [ "$git_ok" -eq 0 ]; then
			info "Cloning UPower source (main branch) — this may take a few minutes..."
			# Capture stderr to a file so we can (a) print it live and
			# (b) extract errors at the end. With `set -e` and
			# `set -o pipefail`, a failed pipeline inside $() can
			# abort the script — see the bash pitfall where
			# `local x=$()` propagates a non-zero exit even with
			# `|| true` at the end of the pipe. So we capture to a
			# file first, then read it.
			# `--filter=blob:none` skips downloading file blobs we
			# won't need (we only patch one C file); cuts clone time
			# noticeably on slow links.
			local git_log=/tmp/pibrick-upower-clone.log
			: > "$git_log"
			if git clone --progress --filter=blob:none --depth=1 \
					https://gitlab.freedesktop.org/upower/upower.git "$UP_SRC" \
					> "$git_log" 2>&1; then
				info "  Clone complete."
			else
				warn "  Clone returned non-zero. Last lines:"
				tail -5 "$git_log" | sed 's/^/    /'
			fi
			# Show errors explicitly (in case the user wants to debug)
			grep -E '(error|fatal|Could not|unable)' "$git_log" 2>/dev/null \
				| head -3 | sed 's/^/    /' || true
			[ -d "$UP_SRC/.git" ] && git_ok=1
		fi
		if [ "$git_ok" -eq 0 ]; then
			error "Failed to clone UPower source from gitlab.freedesktop.org."
			error "Check network:  curl -I https://gitlab.freedesktop.org/upower/upower.git"
			return 1
		fi
		info "UPower source ready."
	fi

	local BAK="${UPowerD}.bak-pibrick-$(date +%Y%m%d%H%M%S)"
	cp "$UPowerD" "$BAK"
	info "Backed up to: $BAK"

	# Replace the current_now discharge detection check in source.
	# UPower mis-detects BQ25895 charging as discharging when current_now is
	# negative.
	UP_FILE="$UP_SRC/src/linux/up-device-supply-battery.c"
	# Write Python patcher to a temp file, then execute it.
	# This avoids all heredoc indentation issues (bash <<- strips ALL leading
	# tabs, which is incompatible with Python syntax). The quoted terminator
	# on the inner heredoc prevents shell-variable expansion of the code.
	cat > /tmp/pibrick-patch-upower.py <<'PYEOF'
import pathlib, sys
path = pathlib.Path(sys.argv[1])
content = path.read_text()
needle = 'g_udev_device_get_sysfs_attr_as_double_uncached (native, "current_now") < 0.0'
if needle in content:
    content = content.replace(
        needle,
        '0 && /* DISABLED: was: current_now < 0 */ g_udev_device_get_sysfs_attr_as_double_uncached (native, "current_now") < 0.0',
        1)
    path.write_text(content)
    print('Source patched: disabled current_now override')
else:
    print('Primary pattern not found -- source may already be modified or differs.')
    print('UPower may not need patching on this version.')
PYEOF
	python3 /tmp/pibrick-patch-upower.py "$UP_FILE"
	# Verify patch was applied (look for our DISABLED marker)
	if grep -q "DISABLED: was: current_now" \
	   "$UP_SRC/src/linux/up-device-supply-battery.c" 2>/dev/null; then
		info "Source patched: disabled current_now override"
	else
		# If the exact pattern was not found, the source may already differ;
		# check whether the original check is still there unmodified.
		if grep -q 'current_now"[^"]*" < 0\.0' \
		   "$UP_SRC/src/linux/up-device-supply-battery.c" 2>/dev/null; then
			info "Primary pattern not found — source may already be modified or differs."
			info "UPower may not need patching on this version."
		else
			info "Patch check inconclusive; continuing with build."
		fi
	fi

	info "Building UPower..."
	cd "$UP_SRC"

	# Install build dependencies required by meson/ninja.
	# meson and ninja are not available via apt on some Debian releases,
	# so install them via pip as a fallback.
	info "Installing UPower build dependencies..."
	if ! apt-get install -y \
			git \
			python3-pip \
			libglib2.0-dev \
			libgcrypt20-dev \
			libdbus-1-dev \
			libgudev-1.0-dev \
			libpolkit-gobject-1-dev \
			pkg-config \
			gir1.2-gudev-1.0 \
			xsltproc \
			docbook-xsl \
			gtk-doc-tools \
			gettext 2>/dev/null; then
		warn "Could not install all build deps -- continuing anyway"
	fi

	# Install meson/ninja via pip if not already available.
	# --break-system-packages is needed on Debian/bookworm+ with externally-managed-env.
	if ! command -v meson >/dev/null 2>&1; then
		info "Installing meson and ninja via pip..."
		if ! pip3 install --break-system-packages meson ninja 2>/dev/null; then
			error "Failed to install meson/ninja."
			return 1
		fi
	fi

	# Remove any stale build dir (may be owned by root from a previous run).
	# Recreate as root so meson/ninja can write without permission errors.
	sudo rm -rf "$UP_SRC/build"
	sudo mkdir -p "$UP_SRC/build"

	# Patch udev_dir into libudev.pc (Debian ships udev_dir as a shell variable,
	# not a pkg-config variable, but UPower's meson.build expects pkg-config access).
	local pcfile=/usr/lib/aarch64-linux-gnu/pkgconfig/libudev.pc
	if [ -f "$pcfile" ] && ! grep -q "^udev_dir=" "$pcfile"; then
		sudo sed -i '/^prefix=/a udev_dir=/lib/udev' "$pcfile"
	fi

	# Also patch udev → libudev in meson.build (Debian uses libudev.pc).
	# Only apply if not already patched.
	if ! grep -q "dependency('libudev'" meson.build 2>/dev/null; then
		sudo sed -i "s/dependency('udev'/dependency('libudev'/g" meson.build 2>/dev/null || true
	fi

	# meson and ninja are installed via pip to /usr/local/bin.
	# Use full paths so they work even when PATH is restricted (e.g. under sudo).
	local MESON=/usr/local/bin/meson
	local NINJA=/usr/local/bin/ninja

	info "Running meson setup..."
	local meson_output
	meson_output=$("$MESON" setup "$UP_SRC/build" --prefix=/usr \
			-Dudevrulesdir=/lib/udev/rules.d \
			-Dudevhwdbdir=/lib/udev/hwdb.d \
			-Dsystemdsystemunitdir=no \
			-Dgtk-doc=false \
			-Dintrospection=disabled \
			-Dman=false 2>&1)
	meson_exit=$?
	echo "$meson_output" | grep -vE '^[+@# ]' | head -20 | sed 's/^/    /'
	if [ "$meson_exit" -ne 0 ]; then
		echo "$meson_output" > /tmp/meson-pibrick.log
		error "meson setup failed. See /tmp/meson-pibrick.log"
		cp "$BAK" "$UPowerD"
		cd /
		return 1
	fi

	info "Compiling UPower (ninja -C build)..."
	local ninja_output
	ninja_output=$("$NINJA" -C "$UP_SRC/build" 2>&1) && ninja_ok=1 || ninja_ok=0
	echo "$ninja_output" | grep -vE '^\[' | head -20 | sed 's/^/    /'
	if [ "$ninja_ok" -eq 0 ]; then
		echo "$ninja_output" > /tmp/ninja-pibrick.log
		error "ninja build failed. See /tmp/ninja-pibrick.log"
		cp "$BAK" "$UPowerD"
		cd /
		return 1
	fi

	if [ ! -f "$UP_SRC/build/src/upowerd" ]; then
		error "Build succeeded but upowerd not found."
		cp "$BAK" "$UPowerD"
		cd /
		return 1
	fi

	safe_cp "$UP_SRC/build/src/upowerd" "$UPowerD"
	cd /

	success "UPower rebuilt successfully."
	restart_upower "$UPowerD"
}

unmask_upower() {
	# Unmask so systemd can manage the service normally.
	# Call this in a trap to guarantee the service is restored even on error.
	systemctl unmask upower 2>/dev/null || true
	systemctl --user unmask upower 2>/dev/null || true
}

stop_upower() {
	# MASK the service FIRST so systemd can't auto-restart it while we work.
	# A trap in fix_upower guarantees we unmask even on error.
	systemctl mask upower 2>/dev/null || true
	systemctl --user mask upower 2>/dev/null || true

	# Stop all upower-related services
	systemctl stop upower 2>/dev/null || true
	systemctl --user stop upower 2>/dev/null || true

	# Kill any running daemons forcefully
	pkill -9 upowerd 2>/dev/null || true

	# Wait for daemon to fully release the file
	sleep 3

	# Verify the daemon stopped
	if pgrep -x upowerd >/dev/null 2>&1; then
		warn "UPower daemon still running, retrying..."
		pkill -9 upowerd 2>/dev/null || true
		sleep 2
	fi

	# If binary is still busy (ETXTBSY), the daemon didn't release it.
	# Try to ensure it's completely gone.
	if [ -f /usr/libexec/upowerd ]; then
		local pid
		pid=$(pgrep -x upowerd 2>/dev/null || true)
		if [ -n "$pid" ]; then
			warn "UPower daemon (PID $pid) still holding binary"
			kill -9 "$pid" 2>/dev/null || true
			sleep 2
		fi
	fi
}

restart_upower() {
	local upowerd_path="${1:-}"
	if [ -z "$upowerd_path" ]; then
		upowerd_path=$(command -v upowerd 2>/dev/null || \
			[ -f /usr/lib/upower/upowerd ] && echo /usr/lib/upower/upowerd || \
			echo /usr/libexec/upowerd)
	fi

	info "Restarting UPower daemon..."
	stop_upower
	unmask_upower
	systemctl start upower 2>/dev/null || "$upowerd_path" &
	sleep 4

	local STATE
	STATE=$(upower -i /org/freedesktop/UPower/devices/battery_battery 2>/dev/null \
		| awk '/^    state:/{print $2}')
	local DRIVER_STATUS
	DRIVER_STATUS=$(cat /sys/class/power_supply/battery/status 2>/dev/null || echo "N/A")
	info "UPower state='$STATE'  driver status='$DRIVER_STATUS'"
	# Normalize to lowercase for comparison (UPower uses lowercase, sysfs may differ).
	local STATE_LC DRIVER_STATUS_LC
	STATE_LC=$(echo "$STATE" | tr '[:upper:]' '[:lower:]')
	DRIVER_STATUS_LC=$(echo "$DRIVER_STATUS" | tr '[:upper:]' '[:lower:]')
	if [ "$STATE_LC" = "$DRIVER_STATUS_LC" ]; then
		success "UPower fix verified."
	else
		warn "UPower state doesn't match driver. Reboot may be needed."
	fi
}

# ── Plasma Mobile KWin fix ─────────────────────────────────────────────────────
# Writes a systemd user drop-in for plasma-kwin_wayland.service that forces
# OpenGL ES 2.0 (KWIN_COMPOSE=O2ES) to fix the black Recent / task-switcher
# on Raspberry Pi V3D driver.
# Requires KDE desktop to be installed first (--install kde-mobile-desktop).
# https://bugs.kde.org/show_bug.cgi?id=519099
fix_plasma_mobile() {
	info "Applying Plasma Mobile KWin fix..."

	if ! kde_packages_available; then
		error "KDE Plasma not installed."
		echo "  Run \`sudo pibrick-tools --install kde-mobile-desktop\` first."
		echo "  This will install kde-standard + sddm and enable the graphical target."
		return 1
	fi

	# ── Derive the desktop user ────────────────────────────────────────────────
	local desk_user=""
	if [ -n "${SUDO_USER:-}" ] && [ "$(id -un)" = "root" ]; then
		desk_user="$SUDO_USER"
	elif command -v loginctl >/dev/null 2>&1; then
		desk_user=$(loginctl show-session \
			"$(loginctl | grep -E '^\s*c[0-9]+' | head -1 | awk '{print $1}' 2>/dev/null)" \
			-p User --value 2>/dev/null)
		desk_user="${desk_user:-$(who | head -1 | awk '{print $1}')}"
	else
		desk_user=$(who | head -1 | awk '{print $1}')
	fi
	[ -z "$desk_user" ] && { error "Cannot determine desktop user."; return 1; }

	# ── Re-apply the KWin drop-in ───────────────────────────────────────────────
	# The KWin drop-in is written by install_kde_mobile_desktop() as part of
	# `pibrick-tools --install kde-mobile-desktop`. That step also handles SDDM
	# and graphical.target. `fix_plasma_mobile()` is now only the "KWin fix"
	# guard — it checks KDE packages are present (done above) and then
	# re-applies the drop-in so running --install kde-mobile-desktop followed by
	# --install plasma-mobile-black-recent-fix also works.

	local zink_flag="${ZINK_FALLBACK:-0}"
	local desk_home
	desk_home=$(getent passwd "$desk_user" | cut -d: -f6)
	desk_home="${desk_home:-/home/$desk_user}"
	local drop_in_dir="$desk_home/.config/systemd/user/plasma-kwin_wayland.service.d"
	local fix_conf="$drop_in_dir/pi-kwin-recent-fix.conf"
	local zink_conf="$drop_in_dir/pi-kwin-zink-fallback.conf"
	local zink_disabled="$drop_in_dir/pi-kwin-zink-fallback.conf.disabled"

	install -d -m 755 "$drop_in_dir"

	cat > "$fix_conf" << 'PLASMAFIX'
[Service]
# Fix black screen in mobile task switcher / overview on Raspberry Pi (KDE bug 519099)
Environment=KWIN_DRM_USE_MODIFIERS=0
Environment=KWIN_COMPOSE=O2ES
Environment=KWIN_PERSISTENT_VBO=1
Environment=KWIN_RENDER_BACKEND=gles
Environment=KWIN_OPENGL_INTERFACE=egl
PLASMAFIX

	if [ "$zink_flag" = "1" ]; then
		cat > "$zink_conf" << 'ZINKFIX'
[Service]
# Fallback when OpenGL ES alone is not enough (higher CPU usage).
Environment=MESA_LOADER_DRIVER_OVERRIDE=zink
ZINKFIX
		rm -f "$zink_disabled"
		info "Zink fallback enabled (software Vulkan via Mesa)."
	else
		rm -f "$zink_conf"
		cat > "$zink_disabled" << 'ZINKDIS'
# Optional fallback if OpenGL ES alone is not enough (higher CPU usage).
# Enable with: ZINK_FALLBACK=1 sudo pibrick-tools --install kde-mobile-desktop
[Service]
Environment=MESA_LOADER_DRIVER_OVERRIDE=zink
ZINKDIS
		info "Zink fallback left disabled (set ZINK_FALLBACK=1 to enable)."
	fi

	su - "$desk_user" -c 'systemctl --user daemon-reload' 2>/dev/null || true

	success "Plasma Mobile KWin fix applied."
	info "Log out and back in (or reboot) for changes to take effect."
}

# ── Install KDE desktop ─────────────────────────────────────────────────────────
# Minimal installer: install required packages, enable SDDM, set graphical.target.
# No fancy preconfigure — default SDDM session selection, default KWin settings.
# Users pick their session on first login at the SDDM greeter.
install_kde_mobile_desktop() {
	info "Setting up KDE desktop..."

	# ── Detect installed packages ───────────────────────────────────────────────
	local have_plasma_mobile=0
	local have_kde_standard=0
	local have_sddm=0

	dpkg -l plasma-mobile 2>/dev/null | grep -q "^ii " && have_plasma_mobile=1
	dpkg -l kde-standard  2>/dev/null | grep -q "^ii " && have_kde_standard=1
	dpkg -l sddm           2>/dev/null | grep -q "^ii " && have_sddm=1

	[ "$have_plasma_mobile" = "1" ] && info "plasma-mobile: installed"  || info "plasma-mobile: not installed"
	[ "$have_kde_standard"  = "1" ] && info "kde-standard: installed"   || info "kde-standard: not installed"
	[ "$have_sddm"          = "1" ] && info "sddm: installed"           || info "sddm: not installed"

	# ── Install missing packages ────────────────────────────────────────────────
	if [ "$have_plasma_mobile" = "0" ] || [ "$have_kde_standard" = "0" ] || [ "$have_sddm" = "0" ]; then
		echo
		echo "Missing packages: plasma-mobile, kde-standard, sddm (~1.3 GB download)"
		echo
		if [ -t 0 ]; then
			local pkgs_reply
			read -r -p "Install packages? [Y/n]: " pkgs_reply || pkgs_reply="y"
			if [[ "${pkgs_reply,,}" == "n" || "${pkgs_reply,,}" == "no" ]]; then
				info "Skipping package installation."
				return 1
			fi
		else
			info "Non-interactive mode — installing packages automatically."
		fi
		install_plasma_packages "$have_plasma_mobile" "$have_kde_standard" "$have_sddm" || return 1
	else
		info "All required packages already installed."
	fi

	# ── Stop / disable any other display manager (lightdm on Raspbian) ──────────
	# Two DMs fighting over VT1 is the most common cause of boot loops.
	for dm in lightdm gdm3 lxdm; do
		systemctl disable "$dm" 2>/dev/null || true
		systemctl stop "$dm" 2>/dev/null || true
		systemctl mask "$dm" 2>/dev/null || true
	done
	systemctl daemon-reload

	# ── Enable SDDM ────────────────────────────────────────────────────────────
	info "Enabling SDDM..."
	systemctl unmask sddm 2>/dev/null || true
	systemctl enable sddm 2>/dev/null || true
	# Don't try to start SDDM if we're already in a graphical session —
	# it would steal the VT. Wait for the next reboot.
	if [ -z "${WAYLAND_DISPLAY:-}" ] && [ -z "${DISPLAY:-}" ]; then
		systemctl start sddm 2>/dev/null || \
			warn "Could not start SDDM now. Reboot to activate."
	else
		info "SDDM will be active after next reboot."
	fi

	# ── Set default target ──────────────────────────────────────────────────────
	local current_target
	current_target=$(systemctl get-default 2>/dev/null || echo "unknown")
	if [ "$current_target" != "graphical.target" ]; then
		info "Setting default target to graphical.target..."
		systemctl set-default graphical.target 2>/dev/null || \
			warn "Could not set default target. Run: sudo systemctl set-default graphical.target"
	else
		info "Default target already graphical.target."
	fi

	success "KDE desktop setup complete."
	echo
	echo "Reboot to start the Plasma Mobile session via SDDM."
	echo "  sudo reboot"
	echo
	echo "Pick the Plasma Mobile session at the SDDM greeter on first login."
}

# ── Install Plasma Mobile packages ────────────────────────────────────────────────
install_plasma_packages() {
	local have_pm=$1 have_ks=$2 have_sd=$3

	info "Installing Plasma Mobile packages (requires network)..."
	info "This may take a while on first run as it downloads ~1-2 GB of packages."

	# Fix any previously interrupted dpkg state before running apt-get.
	# An interrupted apt/dpkg (e.g. Ctrl+C) leaves stale lock files that cause
	# "dpkg was interrupted" errors on every subsequent apt call.
	# Only fix when dpkg is not currently running (fuser checks if lock is live).
	if [ -f /var/lib/dpkg/lock-frontend ]; then
		if command -v fuser >/dev/null 2>&1 && fuser /var/lib/dpkg/lock-frontend >/dev/null 2>&1; then
			info "dpkg is currently running — waiting for it to finish..."
			sleep 5
		else
			info "Detected interrupted dpkg — running dpkg --configure -a..."
			if ! dpkg --configure -a 2>&1 | sed 's/^/    /'; then
				error "dpkg --configure -a failed."
				error "Please run manually: sudo dpkg --configure -a"
				return 1
			fi
		fi
	fi

	# Update package lists
	apt-get update -qq || { warn "apt-get update failed"; return 1; }

	# Build the install list
	local to_install=""
	[ "$have_pm" = "0" ] && to_install="$to_install plasma-mobile"
	[ "$have_ks" = "0" ] && to_install="$to_install kde-standard"
	[ "$have_sd" = "0" ] && to_install="$to_install sddm"

	if [ -z "$to_install" ]; then
		info "Nothing to install."
		return 0
	fi

	# Stream apt output directly so the user sees download + install progress.
	# The `|| { ...; return 1; }` block runs only on apt exit code != 0.
	info "Installing:$to_install"
	if ! apt-get install -y $to_install 2>&1 | grep -v '^Get:\|^Fetched\|^Selecting\|^Preparing\|^Unpacking\|^Setting up\|^Processing '; then
		error "Package installation failed."
		error "Try installing manually: sudo apt install $to_install"
		return 1
	fi

	success "Packages installed: $to_install"
}

