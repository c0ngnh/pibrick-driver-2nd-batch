# ── Prerequisite check + auto-install for fresh Raspberry Pi OS Trixie Lite ────
# On a freshly-flashed Lite image, none of the build tooling or kernel headers
# are pre-installed. The display + battery Makefiles both do
#   make -C /lib/modules/$(uname -r)/build M=$(CURDIR)
# which fails loudly (Makefile not found) when headers are absent. Likewise
# `dtc` (device-tree-compiler), `libgpiod-dev` (button service), `g++` +
# `qt6-{base,declarative}-dev` (autorotation QML plugin) all need an explicit
# apt install on Lite. This function is called once at the top of main(), and
# installs everything the selected components need.
#
# We deliberately do NOT pre-install build tools when no component needs them
# (e.g. `--uninstall autorotation` on a stock image shouldn't pull gcc).
ensure_prerequisites() {
	local needs_kernel_build=0
	local needs_libgpiod=0
	local needs_qt6_dev=0

	[ -n "${INSTALL_DISPLAY:-}" ]      && needs_kernel_build=1
	[ -n "${INSTALL_BATTERY_NEW:-}" ]  && needs_kernel_build=1
	[ -n "${INSTALL_BATTERY_ORIGINAL:-}" ] && needs_kernel_build=1
	[ -n "${INSTALL_BUTTON:-}" ]       && needs_libgpiod=1
	[ -n "${INSTALL_AUTOROTATION:-}" ] && needs_kernel_build=1
	[ -n "${INSTALL_AUTOROTATION:-}" ] && needs_qt6_dev=1

	[ "$needs_kernel_build" = "0" ] && [ "$needs_libgpiod" = "0" ] && \
		[ "$needs_qt6_dev" = "0" ] && return 0

	# apt-get update first so subsequent installs don't hit a stale cache.
	info "Ensuring build prerequisites are installed..."
	apt-get update -qq || { warn "apt-get update failed; builds may fail"; return 0; }

	local pkgs=()

	# Kernel module build requires: kernel headers for the running kernel,
	# basic build toolchain, and dtc for the device-tree overlay.
	if [ "$needs_kernel_build" = "1" ]; then
		local kver
		kver="$(uname -r)"
		local headers_pkg=""
		# Prefer the architecture-specific meta package (linux-headers-rpi-v8
		# on a CM5) which tracks whatever kernel the rpi metapackage pulls
		# in. Fall back to linux-headers-${kver} verbatim — that's what the
		# running kernel is and what `make -C /lib/modules/${kver}/build`
		# will look for.
		if [ -d "/usr/src/linux-headers-${kver}" ]; then
			: # already installed, nothing to do
		else
			case "$(dpkg --print-architecture 2>/dev/null)" in
				aarch64)    headers_pkg="linux-headers-rpi-v8"  ;;
				armv7l|armhf) headers_pkg="linux-headers-rpi"   ;;
				*)          headers_pkg="linux-headers-${kver}" ;;
			esac
			if ! apt-cache show "$headers_pkg" >/dev/null 2>&1; then
				# Fallback if the meta package isn't available in this repo
				headers_pkg="linux-headers-${kver}"
			fi
			pkgs+=("$headers_pkg")
		fi
		command -v gcc       >/dev/null 2>&1 || pkgs+=(gcc)
		command -v make      >/dev/null 2>&1 || pkgs+=(make)
		command -v dtc       >/dev/null 2>&1 || pkgs+=(device-tree-compiler)
		command -v pkg-config >/dev/null 2>&1 || pkgs+=(pkg-config)
		# `bc` is required by some kernel Makefiles for version checks
		command -v bc >/dev/null 2>&1 || pkgs+=(bc)
	fi

	if [ "$needs_libgpiod" = "1" ]; then
		# libgpiod-dev provides the headers; gpiod provides the userland
		# tools that the button service can optionally talk to.
		pkg-config --exists libgpiod 2>/dev/null || pkgs+=(libgpiod-dev gpiod)
	fi

	if [ "$needs_qt6_dev" = "1" ]; then
		# Only required for the autorotation QML plugin. Pure-QML fallback
		# (main.qml) still works without these, but install_quicksetting
		# tries the build. Missing g++/Qt6 should not fail the overall
		# install, so we install quietly and let the autorotation installer
		# warn if it can't build.
		command -v g++ >/dev/null 2>&1 || pkgs+=(g++)
		dpkg -s qt6-base-dev        >/dev/null 2>&1 || pkgs+=(qt6-base-dev)
		dpkg -s qt6-declarative-dev >/dev/null 2>&1 || pkgs+=(qt6-declarative-dev)
	fi

	if [ "${#pkgs[@]}" -eq 0 ]; then
		return 0
	fi

	info "Installing:${pkgs[*]}"
	DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends "${pkgs[@]}" \
		2>&1 | grep -v '^Get:\|^Fetched\|^Selecting\|^Preparing\|^Unpacking\|^Setting up\|^Processing' || {
		warn "apt-get install of prerequisites failed; component builds may fail."
		warn "Install manually:  sudo apt install ${pkgs[*]}"
		# Don't return non-zero — let the installer attempt the build anyway
		# so the user sees the actual error from gcc/make instead of just
		# the apt failure.
		return 0
	}
	success "Prerequisites installed."
}

# ── Reload drivers ─────────────────────────────────────────────────────────────
reload_drivers() {
	info "Reloading drivers..."

	# Display
	if systemctl is-active --quiet pibrick.service 2>/dev/null; then
		systemctl restart pibrick.service
	fi

	# Battery
	if lsmod | grep -q bq25890_battery; then
		sudo -n modprobe -r bq25890_battery 2>/dev/null || true
		sleep 1
		sudo -n modprobe bq25890_battery
		success "Battery driver reloaded"
	fi
}

# ── Install /usr/local/bin/pibrick-tools wrapper ───────────────────────────────
install_pibrick_wrapper() {
	if [ ! -f "$PIBRICK_SRC/tools/pibrick-tools.sh" ]; then
		return 0
	fi
	info "Installing pibrick-tools wrapper at $PIBRICK_WRAPPER..."
	safe_cp "$PIBRICK_SRC/tools/pibrick-tools.sh" "$PIBRICK_WRAPPER"

	# Create pibrick-brightness symlink for legacy button service scripts
	local brightness_src="/usr/lib/pibrick/tools/pibrick-brightness.sh"
	if [ -f "$brightness_src" ]; then
		ln -sf "$brightness_src" /usr/local/bin/pibrick-brightness
		info "Created /usr/local/bin/pibrick-brightness symlink"
	fi

	success "Wrapper installed: $PIBRICK_WRAPPER"
}

# ── Install bash completion for pibrick-tools ───────────────────────────────────
install_bash_completion() {
	local src_completion="$PIBRICK_SRC/tools/pibrick-tools.bash-completion"
	if [ ! -f "$src_completion" ]; then
		return 0
	fi
	local dest_dir=""
	# Prefer /usr/share/bash-completion/completions on Debian/Ubuntu
	if [ -d /usr/share/bash-completion/completions ]; then
		dest_dir=/usr/share/bash-completion/completions
	elif [ -d /etc/bash_completion.d ]; then
		dest_dir=/etc/bash_completion.d
	fi
	if [ -z "$dest_dir" ]; then
		warn "No bash-completion directory found; skipping"
		return 0
	fi
	info "Installing bash completion to $dest_dir/pibrick-tools..."
	safe_cp "$src_completion" "$dest_dir/pibrick-tools"
	success "Bash completion installed (restart shell or 'source' it manually)"
}

# ── Main ───────────────────────────────────────────────────────────────────────
main() {
	# Refuse to run as non-root for any subcommand that modifies the
	# system. Read-only commands (status, help) are allowed without sudo.
	local needs_root=1
	for arg in "$@"; do
		case "$arg" in
			--status|--status-calibration|--battery-status|--version|-h|--help|help)
				needs_root=0 ;;
			--install|--uninstall|--enable-calibration|--disable-calibration|--reset-calibration|--apply-calibration|--battery-config|--battery-check|--enable-upower|--disable-upower|--enable-autorotation|--disable-autorotation|--autorotation-lock|--autorotation-unlock|--check)
				needs_root=1; break ;;
		esac
	done

	if [ "$needs_root" = "1" ] && [ "$(id -u)" != "0" ]; then
		echo "pibrick install.sh: this command modifies the system." >&2
		echo "Please re-run with sudo:" >&2
		echo "  sudo $0 $*" >&2
		exit 1
	fi

	choose_components "$@"

	# Auto-install build prerequisites on fresh images so the kernel module
	# + touch driver + autorotation plugin builds don't fail with "no rule to
	# make target" or "no such file or directory" from make.
	ensure_prerequisites

	# Copy source tree for all installs
	if [ -n "$INSTALL_DISPLAY$INSTALL_BATTERY_NEW$INSTALL_BATTERY_ORIGINAL$INSTALL_CALIBRATION$INSTALL_BUTTON$INSTALL_AUTOROTATION$INSTALL_PHOSH_PI5$INSTALL_ZSH" ]; then
		copy_sources
	fi

	# Panel selection
	local selected_panel="${PANEL:-9203}"
	if [ -n "$INSTALL_DISPLAY" ]; then
		selected_panel=$(choose_panel)
		info "Selected panel: $(panel_label "$selected_panel")"
	fi

	# Install components
	echo
	echo -e "${BOLD}=== Installing Components ===${RESET}"

	[ -n "$INSTALL_DISPLAY" ] && install_display "$selected_panel"
	[ -n "$INSTALL_BATTERY_NEW" ] && install_battery
	[ -n "$INSTALL_BATTERY_ORIGINAL" ] && install_battery_original
	[ -n "$INSTALL_CALIBRATION" ] && install_calibration
	[ -n "$INSTALL_UPower" ] && fix_upower
	[ -n "$INSTALL_KDE_MOBILE_DESKTOP" ] && install_kde_mobile_desktop
	[ -n "$INSTALL_PLASMA_MOBILE" ] && fix_plasma_mobile
	[ -n "$INSTALL_BUTTON" ] && install_button
	[ -n "$INSTALL_AUTOROTATION" ] && install_autorotation
	[ -n "$INSTALL_PHOSH_PI5" ] && install_phosh_pi5
	[ -n "$INSTALL_ZSH" ] && install_zsh

	# Install the global /usr/local/bin/pibrick-tools wrapper so users
	# don't have to remember the install.sh path under /usr/lib/pibrick/.
	# Also install bash completion if a completion dir is available.
	if [ -f "$PIBRICK_SRC/tools/pibrick-tools.sh" ]; then
		install_pibrick_wrapper
		install_bash_completion
	fi

	# Reload
	reload_drivers

	# Summary
	echo
	echo -e "${BOLD}=== Installation Complete ===${RESET}"
	echo "Installed components:"
	[ -n "$INSTALL_DISPLAY" ] && echo "  - Display driver: $(panel_label "$selected_panel")"
	[ -n "$INSTALL_BATTERY_NEW" ] && echo "  - Battery driver (bq25895 + INA228 auto-detect)"
	[ -n "$INSTALL_BATTERY_ORIGINAL" ] && echo "  - Battery driver (bq25895 + INA228 auto-detect)"
	[ -n "$INSTALL_CALIBRATION" ] && echo "  - Calibration tools (logger + auto-calibrator)"
	[ -n "$INSTALL_UPower" ] && echo "  - UPower KDE charging-state fix"
	[ -n "$INSTALL_KDE_MOBILE_DESKTOP" ] && echo "  - KDE Mobile Desktop (SDDM + Plasma Mobile, default session)"
	[ -n "$INSTALL_PLASMA_MOBILE" ] && echo "  - Plasma Mobile KWin fix"
	[ -n "$INSTALL_BUTTON" ] && echo "  - Button service"
	[ -n "$INSTALL_AUTOROTATION" ] && echo "  - Autorotation service (MMA8451Q accelerometer)"
	[ -n "$INSTALL_PHOSH_PI5" ] && echo "  - Phosh-on-Pi5 libwlroots ABI fix"
	[ -n "$INSTALL_ZSH" ] && echo "  - zsh + Oh My Zsh + Powerlevel10k (for the active user)"
	echo
	echo "Use \`pibrick-tools\` for everything from now on:"
	echo "  sudo pibrick-tools --battery-status"
	echo "  sudo pibrick-tools --status-calibration"
	echo "  sudo pibrick-tools --enable-calibration"
	echo "  sudo pibrick-tools --disable-calibration"
	echo "  sudo pibrick-tools --apply-calibration"
	echo "  sudo pibrick-tools --battery-config charge_full_uah 3800mAh --persist"
	echo "  sudo pibrick-tools --install <component>"
	echo "  sudo pibrick-tools --uninstall <component|all>   # reverse an install"
	echo
	echo "Run \`pibrick-tools --help\` for the full command list."
	echo
	[ -n "$INSTALL_DISPLAY" ] && echo "Reboot to apply display changes: sudo reboot"
	[ -n "$INSTALL_KDE_MOBILE_DESKTOP" ] && echo "Reboot to start Plasma Mobile: sudo reboot"
}

main "$@"
