static ssize_t pibrick_display_enable_show(struct device *dev,
					   struct device_attribute *attr,
					   char *buf)
{
	struct visionox_vtdr6110 *ctx = dev_get_drvdata(dev);

	return sprintf(buf, "%d\n", ctx->enabled ? 1 : 0);
}

static ssize_t pibrick_display_enable_store(struct device *dev,
					    struct device_attribute *attr,
					    const char *buf,
					    size_t count)
{
	struct visionox_vtdr6110 *ctx = dev_get_drvdata(dev);

	if (sysfs_streq(buf, "on") || sysfs_streq(buf, "1")) {
		if (!ctx->enabled) {
			drm_panel_enable(&ctx->panel);
			ctx->enabled = true;
		}
	} else if (sysfs_streq(buf, "off") || sysfs_streq(buf, "0")) {
		if (ctx->enabled) {
			drm_panel_disable(&ctx->panel);
			ctx->enabled = false;
		}
	} else {
		return -EINVAL;
	}

	return count;
}

